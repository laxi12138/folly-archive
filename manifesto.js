  function shuffleChar() {
    return glyphs[Math.floor(Math.random() * glyphs.length)];
  }

  function decodeText(el, finalText, duration = 520) {
    if (!el) return;
    if ((el.textContent || '') === finalText) return;
    const source = el.textContent || '';
    const len = Math.max(source.length, finalText.length);
    const revealBase = performance.now();
    el.classList.add('decode-updating');

    function frame(now) {
      const progress = Math.min(1, (now - revealBase) / duration);
      const revealCount = Math.floor(len * progress);
      let out = '';
      for (let i = 0; i < len; i++) {
        const targetChar = finalText[i] || '';
        if (!targetChar) continue;
        out += i < revealCount ? targetChar : shuffleChar();
      }
      el.textContent = out;
      if (progress < 1) {
        requestAnimationFrame(frame);
      } else {
        el.textContent = finalText;
        el.classList.remove('decode-updating');
      }
    }
    requestAnimationFrame(frame);
  }

  function createP(item) {
    const p = document.createElement('p');
    p.textContent = item.text;
    if (item.className) p.className = item.className;
    if (item.preserveLines) p.dataset.preserveLines = 'true';
    return p;
  }

  function renderSection(section) {
    const sectionEl = document.createElement('section');
    sectionEl.id = section.id;
    sectionEl.className = 'manifesto-section';
    sectionEl.dataset.manifestoSection = 'true';

    const code = document.createElement('div');
    code.className = 'manifesto-section-code';
    code.textContent = section.code;
    sectionEl.appendChild(code);

    const h2 = document.createElement('h2');
    h2.textContent = section.title;
    sectionEl.appendChild(h2);

    if (section.subtitle) {
      const sub = document.createElement('div');
      sub.className = 'manifesto-section-subtitle';
      sub.textContent = section.subtitle;
      sectionEl.appendChild(sub);
    }

    if (section.tenetsIntro) {
      const intro = document.createElement('div');
      intro.className = 'manifesto-tenets-intro';
      intro.textContent = section.tenetsIntro;
      sectionEl.appendChild(intro);
    }

    section.content.forEach(item => {
      if (item.type === 'p') {
        sectionEl.appendChild(createP(item));
      } else if (item.type === 'h3') {
        const h3 = document.createElement('h3');
        h3.textContent = item.text;
        sectionEl.appendChild(h3);
      } else if (item.type === 'tenets') {
        const ol = document.createElement('ol');
        ol.className = 'manifesto-tenets-list';
        item.items.forEach(text => {
          const li = document.createElement('li');
          li.textContent = text;
          ol.appendChild(li);
        });
        sectionEl.appendChild(ol);
      } else if (item.type === 'finalLines') {
        const wrap = document.createElement('div');
        wrap.className = 'manifesto-final-lines';
        item.items.forEach(text => {
          const p = document.createElement('p');
          p.textContent = text;
          wrap.appendChild(p);
        });
        sectionEl.appendChild(wrap);
      }
    });

    return sectionEl;
  }

